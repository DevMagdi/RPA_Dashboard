"""In-place repair of pre-existing SQL Server databases (VARCHAR → NVARCHAR).

An installation that was created before the Unicode schema fix still stores its
text in ``VARCHAR`` columns.  The characters are already lost there (`?` for
Arabic), but the *columns* still have to be converted — otherwise every new
Arabic value written after the upgrade is destroyed the same way.

This module is the single generator for that migration:

* :func:`upgrade_statements` builds idempotent ``ALTER TABLE … ALTER COLUMN``
  statements from the live metadata (so the script can never drift from the
  schema the application actually uses);
* :func:`apply` executes them, and is safe to re-run (each statement first
  checks ``sys.columns``/``sys.types`` for the current type);
* ``python -m app.db.unicode_upgrade --print`` emits the SQL for a DBA to
  review and run inside a maintenance window (banks rarely grant the
  application DDL rights).

The checked-in script ``db/migrations/sqlserver/005_unicode_nvarchar_upgrade.sql``
is generated by this module and verified by ``tests/test_arabic_text.py``.
"""

from __future__ import annotations

import argparse
import logging
import sys
from typing import Iterable, List, Optional

from sqlalchemy import MetaData, Unicode, UnicodeText
from sqlalchemy.engine import Engine

from app.core.config import get_settings
from app.db.tables import metadata as default_metadata

logger = logging.getLogger(__name__)

#: SQL Server refuses an index key larger than 1700 bytes (900 for clustered /
#: unique keys before 2016); ``NVARCHAR`` costs two bytes per character, so a
#: text column that is part of an index must stay at or below this length.
MAX_INDEXED_LENGTH = 450

HEADER = """-- ==========================================================================
-- Control Room 4.x — Unicode (NVARCHAR) upgrade for Microsoft SQL Server
-- --------------------------------------------------------------------------
-- WHY: text columns were declared as VARCHAR.  Under a Latin collation a
--      VARCHAR column stores one byte per character, so Arabic process names,
--      audit details and user names were persisted as '????'.  This script
--      converts every text column of the application schema to NVARCHAR so
--      Arabic (and every other non-Latin script) round-trips intact.
--
-- HOW:  run once per database, inside a maintenance window, as a principal
--      with ALTER rights:
--          sqlcmd -S <server> -d <database> -E -i 005_unicode_nvarchar_upgrade.sql
--      The script is idempotent: each statement runs only when the column is
--      not already NVARCHAR.  Values already stored as '?' cannot be restored
--      — re-import those rows from the source platform after the upgrade.
--
-- NOTE: generated from app/db/tables.py — do not edit by hand.  Regenerate:
--          python -m app.db.unicode_upgrade --print > <this file>
-- ==========================================================================

SET NOCOUNT ON;
GO
"""


def _length(column_type: object) -> str:
    """SQL Server length clause for a Unicode column type."""
    if isinstance(column_type, UnicodeText):
        return "MAX"
    length = getattr(column_type, "length", None)
    return str(int(length)) if length else "MAX"


def upgrade_statements(metadata: Optional[MetaData] = None, *, table_filter: Optional[Iterable[str]] = None) -> List[str]:
    """Return the idempotent ``ALTER COLUMN`` block for every Unicode column."""
    meta = metadata or default_metadata
    wanted = {name.lower() for name in table_filter} if table_filter else None
    statements: List[str] = []
    for table in sorted(meta.tables.values(), key=lambda item: item.name):
        table_name = table.name
        if wanted is not None and table_name.lower() not in wanted:
            continue
        columns = [
            column
            for column in table.columns
            if isinstance(column.type, (Unicode, UnicodeText)) and not column.primary_key
        ]
        if not columns:
            continue
        statements.append(f"-- {table_name}")
        for column in columns:
            null_clause = "NULL" if column.nullable else "NOT NULL"
            target = f"NVARCHAR({_length(column.type)})"
            statements.append(
                "IF EXISTS (SELECT 1 FROM sys.columns c JOIN sys.types t ON c.user_type_id = t.user_type_id\n"
                f"           WHERE c.object_id = OBJECT_ID(N'[dbo].[{table_name}]') AND c.name = N'{column.name}'\n"
                "             AND t.name <> N'nvarchar')\n"
                f"  ALTER TABLE [dbo].[{table_name}] ALTER COLUMN [{column.name}] {target} {null_clause};"
            )
        statements.append("GO\n")
    return statements


def oversized_index_columns(metadata: Optional[MetaData] = None) -> List[str]:
    """Indexed text columns whose NVARCHAR key would be too large (2 bytes/char).

    Returns human-readable ``Table.Column`` entries; an empty list means the
    generated migration is safe for SQL Server's index key limit.
    """
    meta = metadata or default_metadata
    problems: List[str] = []
    for table in meta.tables.values():
        indexed = {column.name for column in table.columns if column.index or column.unique}
        for constraint in table.constraints:
            indexed.update(column.name for column in getattr(constraint, "columns", []))
        for index in table.indexes:
            indexed.update(column.name for column in index.columns)
        for column in table.columns:
            if column.name in indexed and isinstance(column.type, Unicode):
                length = getattr(column.type, "length", None) or 0
                if length > MAX_INDEXED_LENGTH:
                    problems.append(f"{table.name}.{column.name} ({length})")
    return problems


def script(metadata: Optional[MetaData] = None) -> str:
    """Full SQL script text (header + statements) for a DBA to run."""
    return HEADER + "\n".join(upgrade_statements(metadata)) + "\n"


def apply(engine: Optional[Engine] = None, *, dry_run: bool = False) -> int:
    """Execute the upgrade against a SQL Server connection; return the count.

    Only meaningful on ``mssql`` — on SQLite/PostgreSQL the Unicode types are
    already ``VARCHAR``/``TEXT`` and no conversion is required.
    """
    from sqlalchemy import text as sql_text

    settings = get_settings()
    if settings.DB_DIALECT != "mssql":
        logger.info("Unicode upgrade not required on dialect=%s", settings.DB_DIALECT)
        return 0

    if engine is None:
        from app.db.session import get_engine

        engine = get_engine()

    count = 0
    with engine.begin() as connection:
        for statement in upgrade_statements():
            if statement.startswith("--") or statement.strip() == "GO":
                continue
            if dry_run:
                print(statement)  # noqa: T201 - CLI output
                continue
            connection.execute(sql_text(statement))
            count += 1
    logger.info("Unicode upgrade applied (%d column definitions checked)", count)
    return count


def main(argv: Optional[List[str]] = None) -> int:
    """CLI: ``--print`` emits the script, ``--apply`` runs it, ``--check`` verifies."""
    parser = argparse.ArgumentParser(description="SQL Server VARCHAR → NVARCHAR upgrade")
    parser.add_argument("--print", action="store_true", help="print the SQL script and exit")
    parser.add_argument("--apply", action="store_true", help="execute the upgrade against DB_DIALECT=mssql")
    parser.add_argument("--check", action="store_true", help="report index-key risks only")
    arguments = parser.parse_args(argv)

    if arguments.print:
        sys.stdout.write(script())
        return 0

    problems = oversized_index_columns()
    if problems:
        print("Indexed text columns that exceed the SQL Server key limit:")  # noqa: T201 - CLI output
        for problem in problems:
            print(f"  - {problem}")  # noqa: T201 - CLI output
        if arguments.check:
            return 2

    if arguments.check and not problems:
        print("Unicode upgrade is safe: no indexed text column exceeds the key limit.")  # noqa: T201

    if arguments.apply:
        applied = apply()
        print(f"Unicode upgrade applied to {applied} column definitions.")  # noqa: T201
    return 0


if __name__ == "__main__":  # pragma: no cover - manual invocation
    raise SystemExit(main())
